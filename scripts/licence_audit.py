"""Write docs/licence_audit.md from installed package metadata (not from memory).

Reads the direct runtime, extra and dev dependencies from pyproject.toml, then each
package's License-Expression / License / Trove classifiers via importlib.metadata.
Prints only counts.
"""

import re
import sys
from importlib import metadata
from pathlib import Path

import tomllib

ROOT = Path(__file__).resolve().parents[1]
PERMISSIVE = ("MIT", "BSD", "APACHE", "ISC", "PSF", "PYTHON SOFTWARE", "HPND", "UNLICENSE", "ZLIB")
WEAK_COPYLEFT = ("MPL", "MOZILLA", "LGPL")


def _name(req: str) -> str:
    return re.split(r"[<>=!~\[; ]", req, maxsplit=1)[0].strip()


def _licence(dist: metadata.Distribution) -> tuple[str, str]:
    md = dist.metadata
    expr = md.get("License-Expression")
    if expr:
        return expr.strip(), "License-Expression"
    classifiers = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or []
                   if c.startswith("License ::")]
    lic = (md.get("License") or "").strip()
    if classifiers:
        return "; ".join(classifiers), "Classifier"
    if lic and len(lic) < 80:
        return lic, "License"
    if lic:
        return lic.splitlines()[0][:80] + " (full text in License field)", "License"
    return "UNKNOWN", "none"


def _verdict(lic: str) -> str:
    up = lic.upper()
    if "GPL" in up and "LGPL" not in up:
        return "FLAG: copyleft (GPL)"
    if any(w in up for w in WEAK_COPYLEFT):
        return "FLAG: weak copyleft (file/library-level); OK to depend on, not to vendor"
    if any(p in up for p in PERMISSIVE):
        return "permissive"
    return "FLAG: unrecognised, check by hand"


def main() -> None:
    proj = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    groups = {"runtime": proj["dependencies"]}
    for extra, reqs in proj.get("optional-dependencies", {}).items():
        groups[f"extra: {extra}" if extra != "dev" else "dev"] = reqs
    rows, flagged, missing = [], 0, 0
    for group, reqs in groups.items():
        for req in reqs:
            name = _name(req)
            try:
                dist = metadata.distribution(name)
                lic, src = _licence(dist)
                ver = dist.version
            except metadata.PackageNotFoundError:
                lic, src, ver = "NOT INSTALLED", "-", "-"
                missing += 1
            verdict = _verdict(lic) if ver != "-" else "FLAG: not installed, unchecked"
            flagged += verdict.startswith("FLAG")
            rows.append(f"| {group} | {name} | {ver} | {lic} | {src} | {verdict} |")
    out = [
        "# Dependency licence audit",
        "",
        "Generated by `scripts/licence_audit.py` from the metadata of the packages installed in",
        f"`.venv` (Python {sys.version.split()[0]}), not from memory. Direct dependencies only",
        "(transitive dependencies are not listed). Versions are not pinned; this is the version",
        "that was installed when the audit ran.",
        "",
        "PreFlight itself is MIT. 'Permissive' = MIT, BSD, Apache-2.0, ISC, PSF or similar.",
        "",
        "| Group | Package | Installed | Licence | Read from | Verdict |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
        f"Flagged: {flagged}. Not installed: {missing}.",
        "",
    ]
    (ROOT / "docs" / "licence_audit.md").write_text("\n".join(out))
    print(f"packages={len(rows)} flagged={flagged} not_installed={missing}")


if __name__ == "__main__":
    main()
